export const getPhrasalVerbsByCategory = (category: PhrasalVerb['category']): PhrasalVerb[] => {
  return phrasalVerbs.filter(pv => pv.category === category);
};

export const getPhrasalVerbsByLevel = (level: number): PhrasalVerb[] => {
  return phrasalVerbs.filter(pv => pv.level <= level);
};

export const getPhrasalVerbsByVerb = (verb: string): PhrasalVerb[] => {
  return phrasalVerbs.filter(pv => pv.verb.toLowerCase() === verb.toLowerCase());
};

