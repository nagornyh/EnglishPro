export const getCollocationsByLevel = (level: CollocationLevel['level']) =>
  collocationsByLevel.find(l => l.level === level)?.collocations || [];

export const getAllCollocations = () =>
  collocationsByLevel.flatMap(l => l.collocations);

export const searchCollocations = (query: string) =>
  getAllCollocations().filter(c =>
    c.collocation.toLowerCase().includes(query.toLowerCase()) ||
    c.translation.toLowerCase().includes(query.toLowerCase())
  );
